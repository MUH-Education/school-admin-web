export interface MockFollowUp {
  id: number
  /** ISO date and time. */
  at: string
  note: string
  by: string
  nextDate: string | null
}

export interface MockEnquiry {
  id: number
  createdOn: string
  parentName: string
  /** Ten digits. The list shows it hidden: 98XXX XX412. */
  phone: string
  relation: EnquiryRelation
  village: string
  childName: string | null
  className: ClassName
  childAge: string | null
  currentSchool: string | null
  source: EnquirySource
  referredBy: string | null
  nextStepDate: string | null
  needsBus: boolean | null
  note: string | null
  status: EnquiryStatus
  lostReason: string | null
  studentId: number | null
  followUps: MockFollowUp[]
}

type Seed = Partial<MockEnquiry> &
  Pick<
    MockEnquiry,
    'id' | 'createdOn' | 'parentName' | 'phone' | 'village' | 'className' | 'source' | 'status'
  >

function enquiry(seed: Seed): MockEnquiry {
  return {
    relation: 'FATHER',
    childName: null,
    childAge: null,
    currentSchool: null,
    referredBy: null,
    nextStepDate: null,
    needsBus: null,
    note: null,
    lostReason: null,
    studentId: null,
    followUps: [],
    ...seed,
  }
}

function followUp(
  id: number,
  day: string,
  hhmm: string,
  by: string,
  note: string,
  nextDate: string | null,
): MockFollowUp {
  return { id, at: `${day}T${hhmm}:00+05:30`, note, by, nextDate }
}

